// Regenerates src/intent/timezones.ts (every zone in zone.tab, with the POSIX
// TZ rule OpenWrt's `system.timezone` takes: the footer of its TZif file) and
// src/intent/countries.ts (the country codes zone.tab lists).
// Run on a machine with tzdata: node scripts/gen-timezones.js
const { readFileSync, writeFileSync } = require("fs");
const dir = process.argv[2] || "/usr/share/zoneinfo";
const zones = readFileSync(`${dir}/zone.tab`, "utf8")
  .split("\n")
  .filter((line) => line && !line.startsWith("#"))
  .map((line) => line.split("\t")[2])
  .concat("UTC") // not in zone.tab, which lists only populated places
  .sort();
const entries = zones.flatMap((zone) => {
  const footer = readFileSync(`${dir}/${zone}`).toString("latin1").trimEnd();
  const rule = footer.slice(footer.lastIndexOf("\n") + 1);
  return rule ? [`  ${JSON.stringify(zone)}: ${JSON.stringify(rule)},`] : [];
});
writeFileSync(
  "src/intent/timezones.ts",
  [
    "// Generated by scripts/gen-timezones.js from tzdata. Do not edit.",
    "// IANA zone name -> the POSIX TZ rule OpenWrt's system.timezone takes.",
    "export const timezones: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n")
);
console.log(`${entries.length} zones`);

// Every country with a zone: the Wi-Fi regulatory domains worth offering.
const countries = [
  ...new Set(
    readFileSync(`${dir}/zone.tab`, "utf8")
      .split("\n")
      .filter((line) => line && !line.startsWith("#"))
      .map((line) => line.split("\t")[0])
  ),
].sort();
writeFileSync(
  "src/intent/countries.ts",
  [
    "// Generated by scripts/gen-timezones.js from tzdata. Do not edit.",
    "// ISO 3166-1 alpha-2 codes, for the Wi-Fi regulatory domain.",
    `export const countries = ${JSON.stringify(countries)};`,
    "",
  ].join("\n")
);
console.log(`${countries.length} countries`);
