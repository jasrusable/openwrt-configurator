// Regenerates src/intent/wifi/regdb.ts from wireless-regdb's db.txt: per
// country, the frequency ranges an access point may transmit in (MHz).
// Ranges marked NO-IR are left out: there a device may only listen, so an
// access point cannot start (it must beacon). DFS ranges stay: legal, with
// radar detection, which hostapd does.
// Run: node scripts/gen-regdb.js [db.txt path or URL]
const { readFileSync, writeFileSync } = require("fs");

const source =
  process.argv[2] || "https://git.kernel.org/pub/scm/linux/kernel/git/wens/wireless-regdb.git/plain/db.txt";

const parse = (text) => {
  const countries = {};
  let current;
  for (const raw of text.split("\n")) {
    const line = raw.replace(/#.*/, "").trim();
    const country = /^country\s+([A-Z0-9]{2})\b/.exec(line);
    if (country) {
      current = country[1];
      countries[current] = [];
      continue;
    }
    if (!current || !line.startsWith("(")) continue;
    // (start - end @ width), (power)[, FLAGS...]
    const rule = /^\(\s*([\d.]+)\s*-\s*([\d.]+)\s*@\s*[\d.]+\s*\)\s*,\s*\([^)]*\)\s*(?:,\s*(.*))?$/.exec(line);
    if (!rule) continue;
    const flags = (rule[3] || "").split(",").map((f) => f.trim().toUpperCase());
    if (flags.includes("NO-IR")) continue;
    const [start, end] = [Number(rule[1]), Number(rule[2])];
    // 2.4, 5 and 6 GHz only.
    if (end < 2400 || start > 7200) continue;
    countries[current].push([start, end]);
  }
  return countries;
};

const main = async () => {
  const text = source.startsWith("http") ? await (await fetch(source)).text() : readFileSync(source, "utf8");
  const countries = parse(text);
  // Only the countries the app offers (gen-timezones.js's list).
  const offered = JSON.parse(/countries = (\[.*\]);/.exec(readFileSync("src/intent/system/countries.ts", "utf8"))[1]);
  const codes = Object.keys(countries).filter((c) => offered.includes(c)).sort();
  if (codes.length < 100) throw new Error(`Only ${codes.length} countries read: not db.txt?`);
  writeFileSync(
    "src/intent/wifi/regdb.ts",
    [
      "// Generated by scripts/gen-regdb.js from wireless-regdb's db.txt. Do not edit.",
      "// Country -> the ranges (MHz) an access point may transmit in (NO-IR left out).",
      "export const regdb: Record<string, readonly (readonly [number, number])[]> = {",
      ...codes.map((c) => `  ${c}: ${JSON.stringify(countries[c])},`),
      "};",
      "",
    ].join("\n")
  );
  console.log(`${codes.length} countries`);
};

main().catch((e) => {
  console.error(e.message);
  process.exit(1);
});
